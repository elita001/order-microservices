"""Creates the admin user, the organization, and the project with a known DSN key.

Run by the glitchtip-init container with `./manage.py shell`. It is idempotent, so the
services can use a DSN from .env and error tracking works without manual setup in the UI.
Development only: a production DSN key is generated by GlitchTip and kept secret.
"""
import os
import uuid

from django.contrib.auth import get_user_model

from apps.organizations_ext.constants import OrganizationUserRole
from apps.organizations_ext.models import Organization
from apps.projects.models import Project, ProjectKey

email = os.environ["GLITCHTIP_ADMIN_EMAIL"]
password = os.environ["GLITCHTIP_ADMIN_PASSWORD"]
dsn_key = uuid.UUID(os.environ["GLITCHTIP_DSN_KEY"])

User = get_user_model()
user = User.objects.filter(email=email).first()
if user is None:
    user = User.objects.create_superuser(email=email, password=password)

org, _ = Organization.objects.get_or_create(slug="orderflow", defaults={"name": "OrderFlow"})
if not org.users.filter(pk=user.pk).exists():
    org.add_user(user, OrganizationUserRole.OWNER)

project, _ = Project.objects.get_or_create(organization=org, name="orderflow", defaults={"platform": "go"})
ProjectKey.objects.get_or_create(public_key=dsn_key, defaults={"project": project, "name": "docker compose"})

print(f"GlitchTip is ready: project {project.id}, DSN http://{dsn_key.hex}@glitchtip:8000/{project.id}")
